import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const sourcePath = resolve(repoRoot, "public/_locales/en/messages.json");
const outputPath = resolve(repoRoot, "src/generated/i18n-types.ts");
const pluralSuffixes = ["zero", "one", "two", "few", "many", "other"];

const localeFile = JSON.parse(readFileSync(sourcePath, "utf8"));
const keys = Object.keys(localeFile).sort();

const placeholderOrder = Object.fromEntries(
  keys.map((key) => [key, getPlaceholderOrder(localeFile[key]?.placeholders)])
);

const pluralBases = [...new Set(keys.flatMap((key) => getPluralBase(key) ?? []))].sort();

const fileContents = `/* eslint-disable */
// This file is auto-generated by scripts/generate-i18n-types.mjs.
// Do not edit by hand.

export const I18N_KEYS = ${JSON.stringify(keys, null, 2)} as const;

export type I18nKey = (typeof I18N_KEYS)[number];

export const I18N_PLACEHOLDER_ORDER = ${JSON.stringify(placeholderOrder, null, 2)} as const;

export type I18nSubstitutionsFor<K extends I18nKey> = Record<
  (typeof I18N_PLACEHOLDER_ORDER)[K][number],
  string | number
>;

export const I18N_PLURAL_BASES = ${JSON.stringify(pluralBases, null, 2)} as const;

export type I18nPluralBase = (typeof I18N_PLURAL_BASES)[number];
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, fileContents);

function getPlaceholderOrder(placeholders) {
  if (!placeholders || typeof placeholders !== "object") {
    return [];
  }

  return Object.entries(placeholders)
    .map(([name, value]) => ({
      name,
      position: getPlaceholderIndex(value?.content)
    }))
    .sort((left, right) => left.position - right.position)
    .map((entry) => entry.name);
}

function getPlaceholderIndex(content) {
  const match = String(content ?? "").match(/\$(\d+)/);
  return match ? Number(match[1]) : Number.MAX_SAFE_INTEGER;
}

function getPluralBase(key) {
  const match = key.match(new RegExp(`^(.*)_(${pluralSuffixes.join("|")})$`));
  return match ? match[1] : null;
}
